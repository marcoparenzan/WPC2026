function New-DemoVerificationCert {
    <#
    .SYNOPSIS
    Creates the proof-of-possession certificate DPS asks for when a CA is verified.
    .DESCRIPTION
    The certificate has the DPS verification code as common name and is signed by the CA being verified.
    .PARAMETER CaDir
    Folder of the CA (ca.pem, ca-key.pem).
    .PARAMETER Code
    Verification code generated by DPS.
    .PARAMETER OutPath
    File that receives the certificate (PEM).
    #>
    param(
        [Parameter(Mandatory)][string]$CaDir,
        [Parameter(Mandatory)][string]$Code,
        [Parameter(Mandatory)][string]$OutPath
    )

    # WHY: DPS wants proof that whoever uploads a CA also owns its private key. It gives a random code;
    # we answer with a certificate whose CN is that code, signed by the CA: only the key owner can produce it.
    $issuer = [Security.Cryptography.X509Certificates.X509Certificate2]::CreateFromPem(
        [IO.File]::ReadAllText((Join-Path $CaDir 'ca.pem')),
        [IO.File]::ReadAllText((Join-Path $CaDir 'ca-key.pem')))

    # Throw-away key pair for the verification certificate: nobody needs it afterwards.
    $curve = [Security.Cryptography.ECCurve]::CreateFromFriendlyName('nistP384')
    $ecdsa = [Security.Cryptography.ECDsa]::Create($curve)

    try {
        $req = [Security.Cryptography.X509Certificates.CertificateRequest]::new(
            "CN=$Code",
            $ecdsa,
            [Security.Cryptography.HashAlgorithmName]::SHA384)

        # Random positive 128-bit serial number (top bit cleared).
        $serial = [byte[]]::new(16)
        [Security.Cryptography.RandomNumberGenerator]::Fill($serial)
        $serial[0] = $serial[0] -band 0x7F

        # Short life (2 days): it is only needed for the moment of the verification.
        $cert = $req.Create(
            $issuer,
            [DateTimeOffset]::UtcNow.AddMinutes(-5),
            [DateTimeOffset]::UtcNow.AddDays(2),
            $serial)

        Write-Pem -Path $OutPath -Label 'CERTIFICATE' -Bytes $cert.RawData
        $cert.Dispose()
    }
    finally {
        $ecdsa.Dispose()
        $issuer.Dispose()
    }
}
