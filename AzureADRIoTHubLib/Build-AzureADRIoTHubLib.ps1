<#
.SYNOPSIS
Joins the function files of AzureADRIoTHubLib (lib\<Area>\<Function>.ps1) into one file, AzureADRIoTHubLib.ps1.

.DESCRIPTION
The library is kept as one file per function, in one folder per area, for readability; the notebooks load a single file, as text, because
the kernel's runspace cannot run .ps1 files under the machine's execution policy and a script loaded as text has no $PSScriptRoot.
This script is the only thing that writes the bundle: edit the area files, then run it.
The bundle is checked to parse, and the functions it defines are listed.

.PARAMETER Check
Does not write anything: exits with 1 when the bundle on disk differs from what would be built (use it in tests).

.EXAMPLE
pwsh -NoProfile -File .\Build-AzureADRIoTHubLib.ps1

.EXAMPLE
pwsh -NoProfile -File .\Build-AzureADRIoTHubLib.ps1 -Check
#>
param([switch]$Check)
$ErrorActionPreference = 'Stop'

# The order matters: a file may use the functions of the files before it.
# Device is the device side (it talks to the real DPS); the payloads stay in Payload, apart from the devices.
$areas  = 'Common', 'Certificates', 'AdrDps', 'Payload', 'Device', 'Launcher', 'Operations', 'Scenario'
$bundle = Join-Path $PSScriptRoot 'AzureADRIoTHubLib.ps1'
$lib    = Join-Path $PSScriptRoot 'lib'

# lib\<Area>\<Function>.ps1: one function per file, sorted by name inside an area (function definitions do not depend on order).
$files = foreach ($a in $areas) {
    $dir = Join-Path $lib $a
    if (-not (Test-Path $dir)) { throw "Missing area folder: lib\$a" }
    $found = @(Get-ChildItem $dir -Filter *.ps1 -File | Sort-Object Name)
    if ($found.Count -eq 0) { throw "Area folder lib\$a has no function files" }
    foreach ($f in $found) { [pscustomobject]@{ Area = $a; Path = $f.FullName; Label = "$a/$($f.Name)" } }
}
$unknown = @(Get-ChildItem $lib -Directory | Where-Object { $_.Name -notin $areas })
if ($unknown) { throw "Folder not listed in `$areas: $($unknown.Name -join ', ')" }

$sb = [System.Text.StringBuilder]::new()
[void]$sb.Append("# AzureADRIoTHubLib.ps1 - GENERATED by Build-AzureADRIoTHubLib.ps1. DO NOT EDIT THIS FILE.`n")
[void]$sb.Append("# Edit the function files in lib\<Area>\ (areas: $($areas -join ', ')) and run the build script again.`n")
[void]$sb.Append("# Load it as text: . ([scriptblock]::Create([IO.File]::ReadAllText(<path>)))   (the kernel cannot run .ps1 files)`n")
$lastArea = $null
foreach ($f in $files) {
    $text = ([IO.File]::ReadAllText($f.Path) -replace "`r`n", "`n").TrimEnd("`n")
    if ($f.Area -ne $lastArea) {
        $lastArea = $f.Area
        [void]$sb.Append("`n# ===== $lastArea " + ('=' * [math]::Max(4, 100 - $lastArea.Length)) + "`n")
    }
    [void]$sb.Append("`n" + $text + "`n")
}
$content = $sb.ToString()

# It must parse, and every area file must define at least one function.
$errors = $null; $tokens = $null
$ast = [System.Management.Automation.Language.Parser]::ParseInput($content, [ref]$tokens, [ref]$errors)
if ($errors.Count -gt 0) { throw "The bundle does not parse: $($errors[0].Message) (line $($errors[0].Extent.StartLineNumber))" }
$names = @($ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $false) | ForEach-Object { $_.Name })
if ($names.Count -ne @($names | Select-Object -Unique).Count) { throw "A function is defined twice: $((($names | Group-Object | Where-Object Count -gt 1).Name) -join ', ')" }

if ($Check) {
    $current = if (Test-Path $bundle) { [IO.File]::ReadAllText($bundle) } else { '' }
    if ($current -ne $content) { Write-Host 'AzureADRIoTHubLib.ps1 is out of date: run Build-AzureADRIoTHubLib.ps1.' -ForegroundColor Red; exit 1 }
    Write-Host "AzureADRIoTHubLib.ps1 is up to date ($($names.Count) functions)."
    exit 0
}
[IO.File]::WriteAllText($bundle, $content, [Text.UTF8Encoding]::new($false))
Write-Host "Written $bundle ($($names.Count) functions): $($names -join ', ')"
